"""Embed the shared workbench as deterministic gzip assets in ESP32 flash."""
from pathlib import Path
import gzip
import tempfile


def generate(root: Path) -> None:
    paths = [root / "esp32_led_control.html", root / "web/styles.css", *sorted((root / "web").glob("*.mjs"))]
    output = ["// Generated by scripts/embed_web.py; do not edit by hand.",
              "#pragma once", "#include <stdint.h>", "#include <stddef.h>",
              "struct WebAsset { const char* path; const char* mime; const uint8_t* data; size_t size; };"]
    entries = []
    for index, path in enumerate(paths):
        source = path.read_bytes()
        if path.suffix == ".html":
            marker = b"<!-- ESP32_DEVICE_MODE -->"
            if source.count(marker) != 1:
                raise ValueError("Expected one device-mode marker in the HTML")
            source = source.replace(marker, b"<script>window.ESP32_DEVICE = true;</script>")
        payload = gzip.compress(source, compresslevel=9, mtime=0)
        # Python versions differ in the gzip OS byte; omit host metadata.
        payload = payload[:9] + b"\xff" + payload[10:]
        output.append(f"static const uint8_t web_asset_{index}[] = {{")
        output.extend(",".join(str(byte) for byte in payload[start:start + 24]) + "," for start in range(0, len(payload), 24))
        output.append("};")
        mime = "text/html; charset=utf-8" if path.suffix == ".html" else "text/css; charset=utf-8" if path.suffix == ".css" else "application/javascript; charset=utf-8"
        route = "/" + path.relative_to(root).as_posix()
        entries.append(f'{{"{route}", "{mime}", web_asset_{index}, sizeof(web_asset_{index})}}')
    output.append("static const WebAsset WEB_ASSETS[] = {" + ",\n".join(entries) + "};")
    content = "\n".join(output) + "\n"
    # Keep a generated copy with the sketch so Arduino IDE needs no PIO paths.
    target = root / "esp32_led_control/web_assets.h"
    target.parent.mkdir(parents=True, exist_ok=True)
    if target.exists() and target.read_text() == content:
        return
    with tempfile.NamedTemporaryFile(mode="w", dir=target.parent, delete=False) as temporary:
        temporary.write(content)
        name = temporary.name
    Path(name).chmod(0o644)
    Path(name).replace(target)


if __name__ == "__main__":
    generate(Path(__file__).resolve().parents[1])
else:
    Import("env")  # type: ignore[name-defined]  # PlatformIO pre-build script.
    generate(Path(env.subst("$PROJECT_DIR")))  # type: ignore[name-defined]
